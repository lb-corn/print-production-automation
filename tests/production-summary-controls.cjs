const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('public/js/app.js', 'utf8');
const nodes = new Map();
const document = {querySelectorAll(selector) {if (!nodes.has(selector)) nodes.set(selector, {textContent:'unchanged'});return [nodes.get(selector)];}};
const context = {document};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function updateWorkspaceStats('), source.indexOf('const workspaceStatus =')), context);
context.updateWorkspaceStats({areas:{bags:{ready:4,active:2,done:3},apparel:{waiting:7,active:1,done:8}}});
assert.equal(nodes.get('[data-summary-count="bags.ready"]').textContent, '4');
assert.equal(nodes.get('[data-summary-count="apparel.waiting"]').textContent, '7');
context.updateWorkspaceStats({ready:9,in_print:5,completed:6});
assert.equal(nodes.get('[data-summary-count="bags.ready"]').textContent, '9');
assert.equal(nodes.get('[data-summary-count="bags.active"]').textContent, '5');
context.updateWorkspaceStats({areas:{apparel:{waiting:null,active:-1}}});
assert.equal(nodes.get('[data-summary-count="apparel.waiting"]').textContent, '\u2014');
assert.equal(nodes.get('[data-summary-count="apparel.active"]').textContent, '1');
console.log('PASS: combined and legacy refresh payloads update the summary; missing and invalid counts stay clear');
